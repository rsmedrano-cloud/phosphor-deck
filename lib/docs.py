"""phosphor help / phosphor docs - one manual, three readers.

doc/manual/*.md is the only source. `phosphor help TOPIC` shows a page in the
terminal; `phosphor docs` builds AGENTS.md (what AI assistants read) from the
same pages: the rules, the concepts page and an index of the rest, not the
whole manual, since assistants load it into every turn. The key table comes
from share/keys.json; `phosphor docs --check` fails when AGENTS.md is out of
date. Edit the manual, never a copy.
"""
import json, os, re, shutil, subprocess, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from ui import *

MAN = os.path.join(REPO, "doc", "manual")
AGENTS = os.path.join(REPO, "AGENTS.md")
ORDER = ["concepts", "tour", "install", "patterns", "profile", "commands", "keys", "phones",
         "workspaces", "mentions", "web", "tunnels", "clipboard", "privacy", "api", "troubleshooting"]

RULES = """# AGENTS.md — Phosphor Deck for AI assistants

GENERATED by `phosphor docs` from doc/manual/*.md. Don't edit it; edit the manual.

## Rules for assistants

- The profile (`~/.config/phosphor/deck.toml`) is the only source of truth.
  Change it (or use `phosphor setup`), then `phosphor gen && phosphor restart`.
  Never edit files marked "GENERATED BY phosphor gen".
- Prefer `phosphor` commands over hand-made zellij/systemd changes; read
  state with `--json` (commands manual, "For scripts") instead of panel text.
- Verify with `phosphor doctor`; read the logs listed in troubleshooting.
- Don't test against the live `deck` session: use a throwaway one
  (`zellij --layout L attach --create-background probe`), and never
  `zellij action new-tab` with no client attached.
- `phosphor restart` closes every pane, possibly the one you run in; from
  inside the deck it detaches itself, and every screen that came in with
  `deck` goes back in by itself.
- The chat feed is read-only: never send, reply or post on the user's behalf.
- Browser access (`phosphor web on`) publishes a terminal: only when the user
  asks, tailnet only, never `tailscale funnel`.
- Keep personal data out of the repo; run `phosphor privacy` before a push.
- Only claim what you checked: run the command, read the file.
- `share/commands.json` is every command's one definition (usage, flags,
  aliases) and says which can mutate live state and which need the deck
  already running: check it before running one unattended. A new command
  or flag is an entry there; help, --help, the menu and completion follow
  (`tests/commands-manifest-check.py`). A new public command also declares
  its `card`, how it shows in the deck (`tests/doors-check.py`).


## Working on Phosphor itself

Before changing anything in this repository, whichever assistant you are,
read doc/maintaining.md: the session protocol, issues as the queue, who does
what, branches, CI, docs and the hard-won rules. Releases: doc/releasing.md.
A pull request from outside: CONTRIBUTING.md.
"""

def page(name):
    txt = open(os.path.join(MAN, name + ".md")).read()
    if "<!-- keys:_deck -->" in txt:
        try:
            k = json.load(open(os.path.join(REPO, "share", "keys.json")))["_deck"]["k"]
            rows = ["| key | action |", "|---|---|"] + \
                   ["| %s | %s |" % (a, b) for a, b in k if a] + [""] + [b for a, b in k if not a]
            txt = txt.replace("<!-- keys:_deck -->", "\n".join(rows))
        except Exception:
            import dlog
            dlog.event("DOCS", "keys-table-failed")   # never str(e): it can quote the install path
    return txt

def demote(txt):
    return re.sub(r"^# ", "## ", re.sub(r"^## ", "### ", txt, flags=re.M), flags=re.M)

def summaries():
    """topic -> its line in the manual's own README table, the one place it's written."""
    rows = re.findall(r"^\| (\w+) \| (.+?) \|$", page("README"), flags=re.M)
    return {t: d for t, d in rows if t != "topic"}

def index():
    """The rest of the manual as pointers: the full text stays one file read away."""
    what = summaries()
    out = ["## The manual", "",
           "Everything else is in doc/manual/, one page per topic (`phosphor help TOPIC`",
           "shows it in a terminal). Read the page a task touches; don't load them all.",
           "Every page's sections, so a grep finds the right one:", ""]
    for n in ORDER[1:]:
        heads = re.findall(r"^###? (.+)$", page(n), flags=re.M)
        out.append("- **%s** (`doc/manual/%s.md`): %s" % (n, n, what.get(n, "")))
        if heads:
            out.append("  Sections: " + "; ".join(heads) + ".")
        if "<!-- keys:_deck -->" in open(os.path.join(MAN, n + ".md")).read():
            out.append("  Its key table comes from share/keys.json (`_deck`); `phosphor help %s` shows it filled in." % n)
    return "\n".join(out)

def build():
    parts = [RULES, demote(page(ORDER[0])), index()]
    return "\n".join(p.rstrip() + "\n" for p in parts)

IMG = re.compile(r"^!\[(.*?)\]\((.*?)\)$")

def render(md, w):
    out = []
    for l in md.splitlines():
        m = IMG.match(l)
        if m:
            # a screenshot: real content on GitLab/GitHub, a caption here --
            # there's no way to show the image itself in a terminal
            out.append(DIM + "  · screenshot: " + (m.group(1) or m.group(2)) + RST)
        elif l.startswith("#"):
            out.append(BLOOM + l.lstrip("# ").upper() + RST)
        elif l.startswith("    "):
            out.append(PH + l + RST)
        elif l.startswith("|"):
            cells = [c.strip() for c in l.strip("|").split("|")]
            if set("".join(cells)) <= set("-: "): continue
            out.append("  " + AMB + cells[0].ljust(18) + RST + FG + "  ".join(cells[1:]) + RST)
        else:
            l = re.sub(r"\*\*(.+?)\*\*", BLOOM + r"\1" + RST, l)
            l = re.sub(r"`([^`]+)`", PH + r"\1" + RST, l)
            out.append(l)
    return "\n".join(out) + "\n"

def help(topic):
    names = [n for n in ORDER if n.startswith(topic)] if topic else []
    if not names:
        print(render(page("README") if os.path.exists(os.path.join(MAN, "README.md")) else "", 80))
        return 0 if not topic else 1
    text = render(page(names[0]), shutil.get_terminal_size((80, 24)).columns)
    if sys.stdout.isatty() and shutil.which("less"):
        import form
        subprocess.run(["less", "-R", "-F", "-X", form.LESS_PROMPT], input=text, text=True)
    else:
        sys.stdout.write(text)
    return 0

def docs(check=False):
    new = build()
    old = open(AGENTS).read() if os.path.exists(AGENTS) else ""
    if check:
        ok = old == new
        print(row(OK if ok else BAD, "AGENTS.md", "up to date" if ok else "out of date: run phosphor docs"))
        return 0 if ok else 1
    open(AGENTS, "w").write(new)
    print(row(OK, "AGENTS.md", "%d lines from %d pages" % (new.count("\n"), len(ORDER))))
    return 0
