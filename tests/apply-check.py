#!/usr/bin/env python3
"""phosphor apply (#124): a changed profile reaches the running deck tab by
tab, a restart only when the engine changed.

Pure: plan() from what gen wrote, holds() from a pane's command line.
Live, in a throwaway zellij (tests/zjprobe.py, its own HOME and socket):
- one tab changed: that tab is reloaded in place, at its place; every other
  tab keeps its panes' pids; no restart.
- a tab holding a shell: without a terminal it's left as it is and pending;
  --yes reloads it.
- a tab added and one taken out: opened at its place, closed.
- [keys] changed: nothing reloaded, the restart is named (config.kdl), and
  it's left pending: never a real restart here (it would reach the live
  deck's service through systemctl).
"""
import json, os, shlex, subprocess, sys, time
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tests")); sys.path.insert(0, os.path.join(ROOT, "lib"))
import zjprobe

fails = []

def need(what, ok, detail=""):
    print(("ok   " if ok else "FAIL ") + what + ("" if ok else "  " + str(detail)[-600:]))
    if not ok: fails.append(what)
    return ok

LAYOUT = '''// GENERATED BY `phosphor gen`
layout {
    default_tab_template {
        BAR
        children
    }
    tab name="A" focus=true {
        pane command="x"
    }
    tab name="B" {
        pane command="y"
    }
}'''

def pure():
    import apply, gen
    prof = {"deck": {"session": "applyck"}, "hosts": [{"name": "box", "role": "brain", "local": True}],
            "tabs": [{"name": "A"}, {"name": "B"}]}
    Z, U = gen.ZDIR, gen.UDIR
    p = apply.plan(LAYOUT, LAYOUT, [os.path.join(Z, "tab-a.kdl"), os.path.join(Z, "applyck.kdl")], prof)
    need("plan: a changed tab layout is reloaded, nothing else", p["reload"] == ["A"] and not p["restart"]
         and not p["add"] and not p["remove"], p)
    added = LAYOUT.replace('    tab name="B" {', '    tab name="C" {\n        pane\n    }\n    tab name="B" {')
    p = apply.plan(LAYOUT, added.replace('    tab name="A" focus=true {\n        pane command="x"\n    }\n', ''),
                   [os.path.join(Z, "tab-c.kdl")], prof)
    need("plan: a new tab is opened, a gone one closed, not reloaded",
         p["add"] == ["C"] and p["remove"] == ["A"] and not p["reload"] and not p["restart"], p)
    swapped = LAYOUT.replace('tab name="A" focus=true', 'tab name="Q"').replace('tab name="B"', 'tab name="A"') \
                    .replace('tab name="Q"', 'tab name="B"')
    p = apply.plan(LAYOUT, swapped, [], prof)
    need("plan: tabs in another order: a restart, said why", any("order" in r for r in p["restart"]), p)
    p = apply.plan(LAYOUT, LAYOUT.replace("BAR", "BAR2"), [], prof)
    need("plan: the bars every tab shares changed: a restart", any("bars" in r for r in p["restart"]), p)
    p = apply.plan(LAYOUT, LAYOUT, [gen.ZCONF], prof)
    need("plan: config.kdl ([keys]) changed: a restart naming it", any("config.kdl" in r for r in p["restart"]), p)
    p = apply.plan(LAYOUT, LAYOUT, [os.path.join(U, "fleet-db-box.service"), os.path.join(U, "applyck.service")], prof)
    need("plan: a mount's unit is (re)started, the deck's own unit restarts it",
         p["units"] == ["fleet-db-box.service"] and any("service" in r for r in p["restart"]), p)
    p = apply.plan(LAYOUT, LAYOUT, [os.path.join(gen.HOME, ".local/bin/deck"), os.path.join(gen.HOME, ".config/rclone/rclone.conf")], prof)
    need("plan: the attach command and rclone.conf need nothing now", not any(p.values()), p)
    p = apply.plan(None, LAYOUT, [], prof)
    need("plan: no earlier layout to compare: a restart", bool(p["restart"]), p)

    need("base: a notice's mark and the edit mark aren't the name",
         [apply.base(n) for n in ("SYS ●3", "SYS ✎ Alt r", "SYS")] == ["SYS"] * 3)
    # zellij busy, answering nothing: never "nothing to lose", never "done"
    saved = apply.panes, apply.tabs
    apply.panes, apply.tabs = (lambda sess: []), (lambda sess: [])
    try:
        need("silent zellij: a tab's panes count as something to lose", bool(apply.keeping("applyck", 0)))
        need("silent zellij: a reload isn't counted as done", apply.reload("applyck", "A") is False
             and apply.close("applyck", "A") is False)
    finally:
        apply.panes, apply.tabs = saved
    PH = os.path.join(ROOT, "phosphor")
    cases = [(["python3", PH, "run", "--name", "SHELL", "--", "/bin/bash", "-l"], "bash"),
             (["python3", PH, "run", "--name", "FLEET", "--", PH, "fleet"], None),
             (["python3", PH, "run", "--name", "BTOP", "--", "/usr/bin/btop"], None),
             (["python3", PH, "run", "--name", "ASK", "--", PH, "ask"], "phosphor ask"),
             (["python3", PH, "run", "--name", "HX", "--", "/usr/bin/hx", "notes.md"], "hx"),
             (["python3", PH, "run", "--name", "SSH", "--reconnect", "--", "ssh", "-t", "db-box"], "ssh"),
             (["python3", PH, "bar"], None), (None, None)]
    for argv, want in cases:
        got = apply.holds(argv)
        need("holds: %s -> %s" % ((argv or ["(gone)"])[-2:], want), got == want, got)

PROFILE = '''
[deck]
session = "applyck"

[[hosts]]
name = "box"
role = "brain"
local = true

[[tabs]]
name  = "A"
panes = [ { cmd = "sleep", args = ["611"] } ]

[[tabs]]
name  = "B"
panes = [ { cmd = "sleep", args = ["612"] } ]

[[tabs]]
name  = "SH"
panes = [ { cmd = "" } ]
'''

def phosphor(z, *args):
    """phosphor in the probe's HOME, no terminal; the client's output read
    meanwhile so the session never waits on it."""
    out = os.path.join(z.home, "out.txt")
    with open(out, "w") as f:
        p = subprocess.Popen([sys.executable, os.path.join(ROOT, "phosphor")] + list(args), env=z.env,
                             stdin=subprocess.DEVNULL, stdout=f, stderr=subprocess.STDOUT, cwd=z.home)
        t0 = time.time()
        while p.poll() is None and time.time() - t0 < 90:
            z.pump(0.2)
        if p.poll() is None:
            p.kill()
    z.pump(1)
    return p.returncode, open(out).read()

def pids(z):
    """{tab name: sorted pids of its panes}."""
    import hotswap
    env = os.environ.copy()
    os.environ["ZELLIJ_SOCKET_DIR"] = z.env["ZELLIJ_SOCKET_DIR"]
    try:
        ps, t0 = [], time.time()          # busy or mid-reload, zellij may answer nothing or an error
        while not ps and time.time() - t0 < 10:
            try:
                ps = [p for p in json.loads(z.action("list-panes", "-a", "-j") or "[]") if not p["is_plugin"]]
            except ValueError:
                ps = []
            if not ps: z.pump(0.3)
        out = {}
        for p in ps:
            out.setdefault(p["tab_name"], []).extend(hotswap.pane_procs(z.session, p["id"]))
        return {k: sorted(v) for k, v in out.items()}
    finally:
        os.environ.clear(); os.environ.update(env)

def ztabs(z, timeout=10):
    """list-tabs as JSON; under load zellij can answer late or with a
    warning mixed in (z.action keeps stderr): asked again until it parses."""
    t0 = time.time()
    while True:
        try:
            got = json.loads(z.action("list-tabs", "-j", "-s") or "x")
            if got: return got
        except ValueError:
            pass
        if time.time() - t0 > timeout: return []
        z.pump(0.3)

def cmdlines(pidlist):
    out = []
    for p in pidlist:
        try: out.append(open("/proc/%d/cmdline" % p).read().replace("\0", " "))
        except OSError: pass
    return " | ".join(out)

def edit_profile(z, old, new):
    path = z.env["PHOSPHOR_PROFILE"]
    text = open(path).read()
    assert old in text, old
    open(path, "w").write(text.replace(old, new, 1))

def pending(z):
    try:
        return json.load(open(os.path.join(z.home, ".local/share/phosphor/apply-pending")))
    except (OSError, ValueError):
        return None

def live():
    with zjprobe.Probe(PROFILE, session="applyck") as z:
        z.pump(2)
        rc, out = phosphor(z, "gen")             # this probe's HOME gets what a real install has
        if not need("live: gen in the probe", rc == 0, out): return
        z.action("go-to-tab-name", "B"); z.pump(1)
        before = pids(z)
        if not need("live: three tabs, each with its process", all(before.get(t) for t in ("A", "B", "SH")), before):
            return

        edit_profile(z, 'args = ["611"]', 'args = ["621"]')
        tid = next((t["tab_id"] for t in ztabs(z) if t["name"] == "A"), None)
        if not need("live: tab A's id", tid is not None, ztabs(z)): return
        z.action("rename-tab-by-id", str(tid), "A ●2"); z.pump(0.5)   # a notice's mark: still A
        rc, out = phosphor(z, "apply")
        after = pids(z)
        need("one tab: apply exits 0", rc == 0, out)
        need("one tab: it says A was reloaded", "reloaded in place" in out and "restart" not in out.lower(), out)
        need("one tab: the tabs keep their order", z.tabs() == ["A", "B", "SH"], (z.tabs(), out))
        need("one tab: A runs its new program", "sleep 621" in cmdlines(after.get("A", [])), cmdlines(after.get("A", [])))
        need("one tab: A's old process is gone", "sleep 611" not in cmdlines(sum(after.values(), [])))
        need("one tab: B and SH keep their pids", after.get("B") == before["B"] and after.get("SH") == before["SH"],
             (before, after))
        focus = [t["name"] for t in ztabs(z) if t["active"]]
        need("one tab: you stay on the tab you were on", focus == ["B"], focus)
        need("one tab: nothing pending", pending(z) is None, pending(z))

        before = after
        edit_profile(z, 'name  = "SH"\npanes = [ { cmd = "" } ]',
                     'name  = "SH"\nsplit = "rows"\npanes = [ { cmd = "" }, { cmd = "sleep", args = ["631"] } ]')
        rc, out = phosphor(z, "apply")
        after = pids(z)
        need("a shell: apply names what it holds", "SH" in out and "holds" in out and "sh" in out, out)
        need("a shell: without a terminal it's left as it is", after.get("SH") == before["SH"], (before, after))
        need("a shell: and pending", (pending(z) or {}).get("tabs") == ["SH"], pending(z))
        # --yes would also restart: only once a dry run says there's no restart to do
        rc, out = phosphor(z, "apply", "--dry-run", "--json")
        try:
            restart = json.loads(out.strip().splitlines()[-1])["plan"]["restart"]
        except (ValueError, IndexError, KeyError):
            restart = ["unreadable: " + out[-300:]]
        if not need("a shell: nothing asks for a restart", not restart, restart): return
        rc, out = phosphor(z, "apply", "--yes")
        after = pids(z)
        need("a shell: --yes reloads it", after.get("SH") != before["SH"]
             and "sleep 631" in cmdlines(after.get("SH", [])), (out, cmdlines(after.get("SH", []))))
        need("a shell: nothing pending after", pending(z) is None, pending(z))

        before = after
        edit_profile(z, '[[tabs]]\nname  = "B"\npanes = [ { cmd = "sleep", args = ["612"] } ]',
                     '[[tabs]]\nname  = "C"\npanes = [ { cmd = "sleep", args = ["641"] } ]')
        rc, out = phosphor(z, "apply")
        after = pids(z)
        need("add/remove: C opened where B was, B closed", z.tabs() == ["A", "C", "SH"], (z.tabs(), out))
        need("add/remove: B's process is gone", "sleep 612" not in cmdlines(sum(after.values(), [])))
        need("add/remove: A and SH keep their pids", after.get("A") == before["A"] and after.get("SH") == before["SH"],
             (before, after))

        # from a pane of the tab that changed (the DECK tab's f): that tab goes last, detached
        before = after
        edit_profile(z, 'args = ["631"]', 'args = ["632"]')
        z.action("go-to-tab-name", "SH"); z.pump(1)
        z.action("move-focus", "up"); z.pump(0.5)
        # the test's own PATH, or gen in a login shell writes another unit PATH (a restart);
        # never --yes here: a restart would reach systemd's real user manager
        open(os.path.join(z.home, "apply.sh"), "w").write(
            "PATH=%s exec %s %s apply\n" % (shlex.quote(z.env["PATH"]),
            sys.executable, os.path.join(ROOT, "phosphor")))
        z.keys(b"sh $HOME/apply.sh\r", 1)
        seen = lambda w: any(w in l for l in z.screen())
        z.wait(lambda: seen("anyway?") or seen("restart the deck now?"), 30)
        if seen("restart the deck now?"):
            z.keys(b"n", 1)
            need("own tab: no restart asked for", False, "\n".join(z.screen()))
        else:
            z.keys(b"y", 1)
        z.wait(lambda: "sleep 632" in cmdlines(pids(z).get("SH", [])) and z.tabs() == ["A", "C", "SH"], 20)
        after = pids(z)
        log = os.path.join(z.home, ".cache/phosphor/apply.log")
        own = open(log).read() if os.path.exists(log) else ""
        need("own tab: it goes last, detached", "apply reload SH" in own, own)
        need("own tab: reloaded once apply is done with the rest", "sleep 632" in cmdlines(after.get("SH", []))
             and "sleep 631" not in cmdlines(sum(after.values(), [])), (own, after))
        need("own tab: at its place, the others untouched",
             z.tabs() == ["A", "C", "SH"] and after.get("A") == before["A"] and after.get("C") == before["C"],
             (z.tabs(), before, after))

        before = after
        edit_profile(z, '[[hosts]]', '[keys]\nedit = "Alt y"\n\n[[hosts]]')
        rc, out = phosphor(z, "apply")
        after = pids(z)
        need("keys: the restart is named, config.kdl", "restart" in out and "config.kdl" in out, out)
        need("keys: nothing reloaded without it", after == before, (before, after))
        need("keys: the restart is left pending", "config.kdl (keys, theme)" in ((pending(z) or {}).get("restart") or []),
             pending(z))
        rc, out = phosphor(z, "apply", "--dry-run", "--json")
        try:
            got = json.loads(out.strip().splitlines()[-1])
        except (ValueError, IndexError):
            got = {}
        need("keys: --json says it, from what was left pending",
             got.get("ok") and any("config.kdl" in r for r in got.get("plan", {}).get("restart", [])), out)

def main():
    pure()
    if zjprobe.zellij():
        try:
            live()
        except Exception:                 # a whole traceback, not one cut by check.sh's tail
            import traceback
            need("live: ran to the end", False, traceback.format_exc()[-1200:])
    else:
        print("skip live: no zellij")
    print("\n%d failed" % len(fails) if fails else "\nall passed")
    return 1 if fails else 0

if __name__ == "__main__":
    sys.exit(main())
